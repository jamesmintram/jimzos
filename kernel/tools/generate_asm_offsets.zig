const std = @import("std");
const layout = @import("thread_layout");

pub fn main(init: std.process.Init.Minimal) !void {
    if (@sizeOf(usize) != 8) {
        @compileError("AArch64 assembly offsets require a 64-bit build host");
    }

    var threaded: std.Io.Threaded = .init(std.heap.page_allocator, .{
        .environ = init.environ,
        .argv0 = .init(init.args),
    });
    defer threaded.deinit();
    const io = threaded.io();

    var arena_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena_state.deinit();
    const args = try init.args.toSlice(arena_state.allocator());
    if (args.len != 2) return error.InvalidArguments;

    const cwd: std.Io.Dir = .cwd();
    if (std.fs.path.dirname(args[1])) |dirname| try cwd.createDirPath(io, dirname);
    const output = try cwd.createFile(io, args[1], .{});
    defer output.close(io);

    var buffer: [4096]u8 = undefined;
    var file_writer = output.writer(io, &buffer);
    const writer = &file_writer.interface;

    try writer.writeAll(
        \\/* Generated by generate_asm_offsets.zig. Do not edit. */
        \\#ifndef JIMZOS_ASM_OFFSETS_H
        \\#define JIMZOS_ASM_OFFSETS_H
        \\
    );
    try writeOffsets(layout.CPUFrame, "CPUFrame", writer);
    try writeOffsets(layout.Thread, "Thread", writer);
    try writer.writeAll("#endif\n");
    try writer.flush();
}

fn writeOffsets(comptime T: type, comptime type_name: []const u8, writer: *std.Io.Writer) !void {
    inline for (@typeInfo(T).@"struct".fields) |field| {
        try writer.print("#define {s}_{s} {d}\n", .{ type_name, field.name, @offsetOf(T, field.name) });
    }
    try writer.print("#define {s}__size {d}\n\n", .{ type_name, @sizeOf(T) });
}
